test("removes a single entry from the forwarding address history", () => {
  const history = { hq: ["hq-1:1", "hq-2:2"], jy: ["jy-1:3"], zx: [] };
  assert.deepEqual(removeForwardingAddressHistory(history, "hq", "hq-1:1"), { hq: ["hq-2:2"], jy: ["jy-1:3"], zx: [] });
  assert.deepEqual(removeForwardingAddressHistory(history, "zx", "missing"), { hq: ["hq-1:1", "hq-2:2"], jy: ["jy-1:3"], zx: [] });
  assert.deepEqual(removeForwardingAddressHistory(["legacy:4"], "hq", "legacy:4"), { hq: [], jy: [], zx: [] });
});

