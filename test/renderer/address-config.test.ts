test("does not emit an empty base path for root addresses", () => {
  assert.equal(normalizeTargetBasePath("/"), undefined);
  assert.equal(normalizeTargetBasePath("//"), undefined);
});

test("keeps a real target base path after trimming trailing slashes", () => {
  assert.equal(normalizeTargetBasePath("/ant///"), "/ant");
});

test("produces a saveable target for a root address", () => {
  const target = targetFromDraft({ id: "hq", name: "hq", address: "http://127.0.0.1:7778/" }, 0);
  assert.equal(target.basePath, undefined);
  assert.equal(getAppConfigValidationError({
    server: { bindHost: "127.0.0.1", port: 8080, timeoutMs: 30000, loggingEnabled: true },
    httpRules: [],
    tcpTargets: [target],
    localValues: {},
    mapValues: {},
    accounts: {},
    cache: { rootDir: "", downloadTarget: "", decryptEnabled: false, autoDownload: false },
  }), undefined);
});

test("defaults a bare legacy-style reqxml address to TCP", () => {
  const target = targetFromDraft({ id: "jy", name: "jy", address: "123.103.83.82:6110" }, 1);
  assert.equal(target.protocol, undefined);
  assert.equal(target.transport, undefined);
});

test("splits forwarding addresses into host and port while preserving protocol and path", () => {
  assert.deepEqual(addressPartsForDraft("tcp://123.103.83.82:6110"), { host: "123.103.83.82", port: "6110" });
  assert.deepEqual(addressPartsForDraft("http://127.0.0.1:8080/ant"), { host: "127.0.0.1", port: "8080" });
  assert.deepEqual(addressPartsForDraft(":6110"), { host: "", port: "6110" });
  assert.equal(addressFromParts("http://127.0.0.1:8080/ant", "10.0.0.2", "9090"), "http://10.0.0.2:9090/ant");
  assert.equal(addressFromParts("123.103.83.82:6110", "123.103.83.83", "6111"), "123.103.83.83:6111");
  assert.equal(addressFromParts("123.103.83.82:6110", "", "6110"), ":6110");
});

test("accepts a complete HTTPS forwarding URL without an explicit port", () => {
  const target = targetFromDraft({ id: "hq", name: "hq", address: "https://h5khtest.citics.com/ant" }, 0);
  assert.equal(target.host, "h5khtest.citics.com");
  assert.equal(target.port, 443);
  assert.equal(target.protocol, "https");
  assert.equal(target.transport, "http");
  assert.equal(target.basePath, "/ant");
});

test("does not display a TCP target as HTTP when legacy protocol metadata is present", () => {
  assert.equal(addressForTarget({ id: "jy", name: "jy", host: "123.103.83.82", port: 6064, protocol: "http" }), "tcp://123.103.83.82:6064");
  assert.equal(addressForTarget({ id: "jy", name: "jy", host: "123.103.83.82", port: 6064, protocol: "http", transport: "http" }), "http://123.103.83.82:6064");
});

test("saves and reloads the forwarding target generated by the address form", async () => {
  const directory = await mkdtemp(path.join(os.tmpdir(), "local-forwarder-address-save-"));
  const target = targetFromDraft({ id: "hq", name: "hq", address: "http://127.0.0.1:7778//" }, 0);
  const config = {
    server: { bindHost: "127.0.0.1", port: 8080, timeoutMs: 30000, loggingEnabled: true },
    httpRules: [],
    tcpTargets: [target],
    localValues: {},
    mapValues: {},
    accounts: {},
    cache: { rootDir: "", downloadTarget: "", decryptEnabled: false, autoDownload: false },
  };
  try {
    const store = new ConfigStore(path.join(directory, "internal.json"));
    await store.save(config);
    const restored = await store.load();
    assert.deepEqual(restored.tcpTargets, [target]);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
});

