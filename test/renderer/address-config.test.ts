test("keeps recent forwarding addresses unique and newest first", () => {
  assert.deepEqual(
    appendForwardingAddressHistory(["10.0.0.12:7776", "123.103.83.82:7776"], " 123.103.83.82:7776 "),
    ["123.103.83.82:7776", "10.0.0.12:7776"],
  );
});

test("limits forwarding address history to the ten most recent entries", () => {
  const history = Array.from({ length: 10 }, (_, index) => `10.0.0.${index}:7776`);
  assert.deepEqual(appendForwardingAddressHistory(history, "10.0.0.99:7776"), ["10.0.0.99:7776", ...history.slice(0, 9)]);
});

test("keeps market, trading, and news forwarding histories separate", () => {
  const history = { hq: ["hq.example:7776"], jy: ["jy.example:7776"], zx: ["zx.example:7776"] };
  assert.deepEqual(forwardingAddressHistoryForTarget(history, "hq"), ["hq.example:7776"]);
  assert.deepEqual(forwardingAddressHistoryForTarget(history, "jy"), ["jy.example:7776"]);
  assert.deepEqual(forwardingAddressHistoryForTarget(history, "zx"), ["zx.example:7776"]);
  assert.deepEqual(forwardingAddressHistoryForTarget(["legacy.example:7776"], "hq"), []);
});

